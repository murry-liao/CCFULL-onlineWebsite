"""Select the gfortran that generates code for this Python's CPU architecture.

The linked CCFULL library is loaded into the running Python process, so it must
match the interpreter.  On Apple silicon an Intel Homebrew gfortran under
/usr/local can precede the native compiler on PATH; such compilers are skipped
instead of producing a library that cannot be loaded.
"""

from __future__ import annotations

from functools import lru_cache
import os
from pathlib import Path
import platform
import subprocess


_ARCHITECTURES = {"aarch64": "arm64", "arm64": "arm64",
                  "amd64": "x86_64", "x86_64": "x86_64"}


def machine() -> str:
    """Normalized CPU architecture of the running Python interpreter."""
    name = platform.machine().lower()
    return _ARCHITECTURES.get(name, name)


def _target(compiler: Path) -> str | None:
    """Architecture of the code generated by one gfortran executable."""
    try:
        triple = subprocess.run(
            [str(compiler), "-dumpmachine"], capture_output=True, text=True,
            timeout=30, check=True).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return None
    name = triple.split("-", 1)[0].lower()
    return _ARCHITECTURES.get(name, name)


@lru_cache(maxsize=1)
def gfortran() -> str:
    """Return the first gfortran on PATH that targets this Python's architecture."""
    found: dict[Path, str | None] = {}
    for folder in os.environ.get("PATH", "").split(os.pathsep):
        candidate = Path(folder or ".") / "gfortran"
        if not (candidate.is_file() and os.access(candidate, os.X_OK)):
            continue
        resolved = candidate.resolve()
        if resolved in found:
            continue
        found[resolved] = _target(candidate)
        if found[resolved] == machine():
            return str(candidate)
    listed = ", ".join(f"{path} -> {target or 'unknown'}" for path, target in found.items())
    raise RuntimeError(
        f"no gfortran on PATH generates {machine()} code for this Python "
        f"(found: {listed or 'none'}); install a native gfortran or put it "
        "first on PATH")
